    #[test]
    fn a_release_is_taken_by_its_barcode_only_where_the_code_agrees_and_names_one_group() {
        let upc = Barcode::new("035627515026").expect("a barcode");
        let taken = the_release_barcoded(
            vec![
                barcoded(RECORDING, Some(ANOTHER_GROUP), "5099902894225"),
                barcoded(RELEASE, Some(GROUP), "0035627515026"),
            ],
            &upc,
        )
        .map(NamedAlbum::linked);

        assert_eq!(
            taken,
            Some(Linked::Album {
                group: mbid(GROUP),
                release: Some(mbid(RELEASE)),
                title: "Whenever You Need Somebody".to_owned(),
                artist: Some("Rick Astley".to_owned()),
            })
        );
        assert_eq!(
            the_release_barcoded(
                vec![
                    barcoded(RELEASE, Some(GROUP), "035627515026"),
                    barcoded(RECORDING, Some(ANOTHER_GROUP), "035627515026"),
                ],
                &upc
            ),
            None,
            "a code two groups share names neither"
        );
        assert_eq!(
            the_release_barcoded(vec![barcoded(RELEASE, None, "035627515026")], &upc),
            None
        );
        assert_eq!(
            the_release_barcoded(vec![barcoded(RELEASE, Some(GROUP), "5099902894225")], &upc),
            None,
            "a release found under another code is no match"
        );
    }

    fn reading(title: &str, artist: &str) -> Reading {
        Reading {
            title: title.to_owned(),
            artist: artist.to_owned(),
        }
    }

    #[test]
    fn an_upload_titled_artist_dash_song_is_read_as_that_song_by_that_artist() {
        assert_eq!(
            readings_of(
                "Rick Astley - Never Gonna Give You Up (Official Music Video)",
                Some("Rick Astley")
            ),
            [reading("Never Gonna Give You Up", "Rick Astley")]
        );
        assert_eq!(
            readings_of(
                "Rick Astley - Never Gonna Give You Up [Official Video] (4K Remaster)",
                Some("RickAstleyVEVO")
            ),
            [
                reading(
                    "Never Gonna Give You Up [Official Video] (4K Remaster)",
                    "Rick Astley"
                ),
                reading(
                    "Rick Astley - Never Gonna Give You Up [Official Video] (4K Remaster)",
                    "RickAstleyVEVO"
                ),
            ],
            "a bracket outside the closed list stays, and so does whatever stands before it"
        );
        assert_eq!(
            readings_of(
                "Never Gonna Give You Up (Audio)",
                Some("Rick Astley - Topic")
            ),
            [reading("Never Gonna Give You Up", "Rick Astley")]
        );
        assert_eq!(
            readings_of("Never Gonna Give You Up (Live)", Some("Rick Astley")),
            [reading("Never Gonna Give You Up (Live)", "Rick Astley")],
            "a take that is another recording keeps what says so"
        );
        assert!(readings_of("Never Gonna Give You Up", None).is_empty());
        assert_eq!(readings_of("Official Video", Some("Rick Astley")).len(), 1);
    }

