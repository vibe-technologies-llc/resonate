struct Address<'a> {
    rest: &'a str,
    host: String,
    segments: Vec<&'a str>,
    query: &'a str,
}

impl<'a> Address<'a> {
    fn read(text: &'a str) -> Option<Self> {
        let rest = text
            .strip_prefix(SECURE)
            .or_else(|| text.strip_prefix(PLAIN))?;
        let rest = rest.split('#').next().unwrap_or(rest);
        let (address, query) = rest.split_once('?').unwrap_or((rest, ""));
        let (host, path) = address.split_once('/').unwrap_or((address, ""));
        let host = host.to_ascii_lowercase();
        let host = host.strip_prefix("www.").unwrap_or(&host).to_owned();
        let segments = path
            .split('/')
            .filter(|segment| !segment.is_empty())
            .collect();

        Some(Self {
            rest,
            host,
            segments,
            query,
        })
    }

    fn is_on_musicbrainz(&self) -> bool {
        self.host == "musicbrainz.org" || self.host.ends_with(".musicbrainz.org")
    }

    fn after(&self, page: &str) -> Option<&'a str> {
        self.segments
            .windows(2)
            .find(|pair| pair[0] == page)
            .map(|pair| pair[1])
    }

    fn names_an_id_after(&self, page: &str) -> bool {
        self.segments
            .windows(2)
            .any(|pair| pair[0] == page && names_an_id(pair[1]))
    }

    fn first(&self) -> Option<&'a str> {
        self.segments.first().copied()
    }

    fn elsewhere(&self) -> String {
        format!("{SECURE}{}", self.rest)
    }
}

fn one_token(text: &str) -> Option<&str> {
    let text = text.trim();
    (!text.is_empty() && !text.contains(char::is_whitespace)).then_some(text)
}

impl SongLink {
    pub fn read(text: &str) -> Option<Self> {
        let text = one_token(text)?;
        if let Some(id) = text.strip_prefix(SPOTIFY_TRACK) {
            return names_an_id(id).then(|| Self::Elsewhere(format!("{SPOTIFY_TRACK_PAGE}{id}")));
        }
        let address = Address::read(text)?;

        if address.is_on_musicbrainz() {
            return match address.segments.as_slice() {
                ["recording", id, ..] => Mbid::new(id).ok().map(Self::MusicBrainz),
                _ => None,
            };
        }
        if address.host == "deezer.com" {
            return address.after("track")?.parse().ok().map(Self::Deezer);
        }

        names_a_song(&address).then(|| Self::Elsewhere(address.elsewhere()))
    }

    pub fn page(&self) -> Option<String> {
        match self {
            Self::Elsewhere(url) if url.starts_with(SONG_LINK_PAGES) => Some(url.clone()),
            Self::Elsewhere(url) => Some(format!(
                "{SONG_LINK_PAGES}{}",
                share::escaped_for_a_path(url)
            )),
            Self::MusicBrainz(_) | Self::Deezer(_) => None,
        }
    }
}

impl AlbumLink {
    pub fn read(text: &str) -> Option<Self> {
        let text = one_token(text)?;
        if let Some(id) = text.strip_prefix(SPOTIFY_ALBUM) {
            return names_an_id(id).then(|| Self::Elsewhere(format!("{SPOTIFY_ALBUM_PAGE}{id}")));
        }
        let address = Address::read(text)?;

        if address.is_on_musicbrainz() {
            return match address.segments.as_slice() {
                ["release", id, ..] => Mbid::new(id).ok().map(Self::Release),
                ["release-group", id, ..] => Mbid::new(id).ok().map(Self::Group),
                _ => None,
            };
        }
        if address.host == "deezer.com" {
            return address.after("album")?.parse().ok().map(Self::Deezer);
        }

        names_an_album(&address).then(|| Self::Elsewhere(address.elsewhere()))
    }

    pub fn page(&self) -> Option<String> {
        match self {
            Self::Elsewhere(url) if url.starts_with(ALBUM_LINK_PAGES) => Some(url.clone()),
            Self::Elsewhere(url) => Some(format!(
                "{ALBUM_LINK_PAGES}{}",
                share::escaped_for_a_path(url)
            )),
            Self::Release(_) | Self::Group(_) | Self::Deezer(_) => None,
        }
    }
}

impl ArtistLink {
    pub fn read(text: &str) -> Option<Self> {
        let text = one_token(text)?;
        if let Some(id) = text.strip_prefix(SPOTIFY_ARTIST) {
            return names_an_id(id)
                .then(|| Self::Elsewhere(format!("https://open.spotify.com/artist/{id}")));
        }
        let address = Address::read(text)?;

        if address.is_on_musicbrainz() {
            return match address.segments.as_slice() {
                ["artist", id, ..] => Mbid::new(id).ok().map(Self::MusicBrainz),
                _ => None,
            };
        }
        if address.host == "deezer.com" {
            return address.after("artist")?.parse().ok().map(Self::Deezer);
        }
        artist_page(&address).map(Self::Elsewhere)
    }

    pub fn pages(&self) -> Vec<String> {
        match self {
            Self::MusicBrainz(_) => Vec::new(),
            Self::Deezer(artist) => vec![format!("{DEEZER_ARTIST_PAGE}{artist}")],
            Self::Elsewhere(page) => {
                let in_every_storefront = apple_music_storefront(page)
                    .filter(|storefront| *storefront != APPLE_MUSIC_IN_EVERY_STOREFRONT)
                    .map(|storefront| {
                        page.replacen(
                            &format!("/{storefront}/"),
                            &format!("/{APPLE_MUSIC_IN_EVERY_STOREFRONT}/"),
                            1,
                        )
                    });
                std::iter::once(page.clone())
                    .chain(in_every_storefront)
                    .collect()
            }
        }
    }
}

fn apple_music_storefront(page: &str) -> Option<&str> {
    page.strip_prefix("https://music.apple.com/")?
        .split('/')
        .next()
}

fn artist_page(address: &Address<'_>) -> Option<String> {
    let segments = address.segments.as_slice();
    let id_after = |page: &str| address.after(page).filter(|id| names_an_id(id));

    match address.host.as_str() {
        "open.spotify.com" | "play.spotify.com" => {
            id_after("artist").map(|id| format!("https://open.spotify.com/artist/{id}"))
        }
        "tidal.com" | "listen.tidal.com" => {
            id_after("artist").map(|id| format!("https://tidal.com/artist/{id}"))
        }
        "music.apple.com" | "itunes.apple.com" => {
            let storefront = segments
                .first()
                .filter(|storefront| storefront.len() == 2)
                .unwrap_or(&APPLE_MUSIC_IN_EVERY_STOREFRONT);
            segments
                .iter()
                .position(|segment| *segment == "artist")
                .and_then(|at| segments[at + 1..].last())
                .map(|id| id.trim_start_matches("id"))
                .filter(|id| !id.is_empty() && id.bytes().all(|byte| byte.is_ascii_digit()))
                .map(|id| format!("https://music.apple.com/{storefront}/artist/{id}"))
        }
        "music.youtube.com" => {
            id_after("channel").map(|id| format!("https://music.youtube.com/channel/{id}"))
        }
        "youtube.com" | "m.youtube.com" => {
            id_after("channel").map(|id| format!("https://www.youtube.com/channel/{id}"))
        }
        "soundcloud.com" | "m.soundcloud.com" => match segments {
            [account]
                if !SOUNDCLOUD_PAGES_NAMING_NO_ARTIST.contains(account) && names_an_id(account) =>
            {
                Some(format!(
                    "https://soundcloud.com/{}",
                    account.to_ascii_lowercase()
                ))
            }
            _ => None,
        },
        host if host.ends_with(".bandcamp.com") && segments.is_empty() => {
            Some(format!("https://{host}/"))
        }
        host if host.starts_with("music.amazon.") => {
            id_after("artists").map(|id| format!("https://music.amazon.com/artists/{id}"))
        }
        _ => None,
    }
}

impl FollowedLink {
    pub fn read(text: &str) -> Option<Self> {
        SongLink::read(text)
            .map(Self::Song)
            .or_else(|| AlbumLink::read(text).map(Self::Album))
            .or_else(|| ArtistLink::read(text).map(Self::Artist))
            .or_else(|| PlaylistLink::read(text).map(Self::Playlist))
    }
}

impl PlaylistLink {
    pub fn read(text: &str) -> Option<Self> {
        let text = one_token(text)?;
        if let Some(id) = text.strip_prefix(SPOTIFY_PLAYLIST) {
            return names_a_spotify_id(id).then(|| Self::Spotify(id.to_owned()));
        }
        let address = Address::read(text)?;

        match address.host.as_str() {
            "open.spotify.com" => address
                .after("playlist")
                .filter(|id| names_a_spotify_id(id))
                .map(|id| Self::Spotify(id.to_owned())),
            "deezer.com" => address.after("playlist")?.parse().ok().map(Self::Deezer),
            "listenbrainz.org" => match address.segments.as_slice() {
                ["playlist", id, ..] => Mbid::new(id).ok().map(Self::ListenBrainz),
                _ => None,
            },
            "youtube.com" | "m.youtube.com" | "music.youtube.com" => (address.first()
                == Some("playlist"))
            .then(|| asked_for(address.query, "list"))
            .flatten()
            .filter(|list| names_an_id(list) && !list.starts_with(YOUTUBE_MUSIC_ALBUMS))
            .map(|list| Self::Youtube(list.to_owned())),
            "music.apple.com" => match address.segments.as_slice() {
                [storefront, "playlist", .., id] if names_a_storefront(storefront) => {
                    names_an_apple_music_playlist(id).then(|| Self::AppleMusic {
                        storefront: (*storefront).to_owned(),
                        id: (*id).to_owned(),
                    })
                }
                _ => None,
            },
            _ => None,
        }
    }
}

fn names_a_storefront(storefront: &str) -> bool {
    storefront.len() == 2 && storefront.chars().all(|letter| letter.is_ascii_lowercase())
}

fn names_an_apple_music_playlist(id: &str) -> bool {
    id.strip_prefix(APPLE_MUSIC_PLAYLIST).is_some_and(|rest| {
        !rest.is_empty()
            && rest
                .chars()
                .all(|glyph| glyph.is_ascii_alphanumeric() || glyph == '-')
    })
}

const HELD_UNDER_THE_ID: &str = "SELECT id, name FROM artists WHERE mbid = ?1 ORDER BY id LIMIT 1";

const HELD_UNDER_THE_NAME: &str = "SELECT id, name FROM artists WHERE key = ?1";

pub(crate) enum ArtistHeldBy<'a> {
    Id(&'a Mbid),
    Name(&'a str),
}

pub(crate) fn artist_held(connection: &Connection, by: ArtistHeldBy<'_>) -> Result<Option<Linked>> {
    let (sql, asked) = match by {
        ArtistHeldBy::Id(mbid) => (HELD_UNDER_THE_ID, mbid.as_str().to_owned()),
        ArtistHeldBy::Name(name) => (HELD_UNDER_THE_NAME, store::folded_letters(name)),
    };
    connection
        .query_row(sql, params![asked], |row| {
            Ok((row.get::<_, i64>(0)?, row.get::<_, String>(1)?))
        })
        .optional()
        .map_err(|source| Error::store(StoreOp::Query, source))?
        .map(|(id, name)| {
            Ok(Linked::HeldArtist {
                artist: ArtistId::new(id as u64)?,
                name,
            })
        })
        .transpose()
}

