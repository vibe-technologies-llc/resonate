fn channel_named(artist: &str) -> Option<&str> {
    let artist = artist.trim();
    let artist = artist
        .strip_suffix(AN_AUTOGENERATED_CHANNEL)
        .unwrap_or(artist)
        .trim();
    (!artist.is_empty()).then_some(artist)
}

fn as_billed(title: &str) -> Option<(&str, &str)> {
    let (before, after) = title.split_once(BETWEEN_ARTIST_AND_TITLE)?;
    let (before, after) = (before.trim(), after.trim());
    (!before.is_empty() && !after.is_empty()).then_some((before, after))
}

fn readings_of(title: &str, artist: Option<&str>) -> Vec<Reading> {
    let artist = artist.and_then(channel_named);
    let mut readings = Vec::new();
    match (as_billed(title), artist) {
        (Some((before, after)), Some(artist)) if enrich::names_agree(before, artist) => {
            readings.push(Reading::of(after, artist));
        }
        (billed, artist) => {
            if let Some((before, after)) = billed {
                readings.push(Reading::of(after, before));
            }
            if let Some(artist) = artist {
                readings.push(Reading::of(title, artist));
            }
        }
    }
    readings.dedup();
    readings
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Footage {
    Heard,
    Filmed,
}

impl Footage {
    pub(crate) fn of(link: &SongLink) -> Self {
        match link {
            SongLink::Elsewhere(page) if Service::of_url(page) == Service::Youtube => Self::Filmed,
            SongLink::MusicBrainz(_) | SongLink::Deezer(_) | SongLink::Elsewhere(_) => Self::Heard,
        }
    }
}

pub(crate) fn the_song_searched_for(
    reference: &dyn Reference,
    song: &LinkNames,
    footage: Footage,
) -> Result<Option<Recording>> {
    let Some(title) = song.title.as_deref() else {
        return Ok(None);
    };
    let readings = readings_of(title, song.artist.as_deref());

    if let Some(heard) = the_first_named(reference, &readings, song.length, |found, named| {
        enrich::the_recording_named(found, named)
    })? {
        return Ok(Some(heard));
    }
    let Some(ran) = song.length.filter(|_| footage == Footage::Filmed) else {
        return Ok(None);
    };

    the_first_named(reference, &readings, None, |found, named| {
        enrich::the_recording_a_video_names(found, named, ran)
    })
}

fn the_first_named(
    reference: &dyn Reference,
    readings: &[Reading],
    length: Option<Duration>,
    taken: impl Fn(Vec<RecordingMatch>, &NamedAs<'_>) -> Option<RecordingMatch>,
) -> Result<Option<Recording>> {
    for reading in readings {
        let named = NamedAs {
            title: &reading.title,
            artist: Some((&reading.artist, None)),
            length,
        };
        for wording in [Wording::Phrase, Wording::Words] {
            let found = reference.find_recording(&RecordingAsked {
                title: reading.title.clone(),
                artist: Some(reading.artist.clone()),
                artist_mbid: None,
                release: None,
                length,
                wording,
            })?;
            if let Some(top) = taken(found, &named) {
                return Ok(Some(
                    reference
                        .recording(&top.recording)?
                        .unwrap_or_else(|| top.into_recording()),
                ));
            }
        }
    }

    Ok(None)
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct NamedAlbum {
    group: Mbid,
    release: Option<Mbid>,
    title: String,
    credit: Vec<Credit>,
}

impl NamedAlbum {
    fn billed(credit: &[Credit]) -> Option<String> {
        let billed = credited_as(credit);
        (!billed.trim().is_empty()).then_some(billed)
    }

    pub(crate) fn linked(self) -> Linked {
        Linked::Album {
            artist: Self::billed(&self.credit),
            group: self.group,
            release: self.release,
            title: self.title,
        }
    }
}

pub(crate) fn album_named(
    reference: &dyn Reference,
    link: &AlbumLink,
) -> Result<Option<NamedAlbum>> {
    match link {
        AlbumLink::Group(group) => Ok(reference.release_group(group)?.map(|group| NamedAlbum {
            group: group.id,
            release: None,
            title: group.title,
            credit: group.credit,
        })),
        AlbumLink::Release(release) => Ok(reference.release(release)?.and_then(|release| {
            Some(NamedAlbum {
                group: release.group?,
                release: Some(release.id),
                title: release.title,
                credit: release.credit,
            })
        })),
        AlbumLink::Deezer(_) | AlbumLink::Elsewhere(_) => {
            let Some(names) = reference.album_linked(link)? else {
                return Ok(None);
            };
            for barcode in &names.barcodes {
                let found = reference.releases_by_barcode(barcode)?;
                if let Some(named) = the_release_barcoded(found, barcode) {
                    return Ok(Some(named));
                }
            }
            Ok(None)
        }
    }
}

pub(crate) fn the_release_barcoded(
    found: Vec<BarcodeMatch>,
    barcode: &Barcode,
) -> Option<NamedAlbum> {
    let barcoded: Vec<BarcodeMatch> = found
        .into_iter()
        .filter(|found| {
            found.group.is_some()
                && found
                    .barcode
                    .as_deref()
                    .is_some_and(|stated| barcode.names(stated))
        })
        .collect();
    let groups: AHashSet<&Mbid> = barcoded
        .iter()
        .filter_map(|found| found.group.as_ref())
        .collect();
    if groups.len() > 1 {
        tracing::debug!(%barcode, groups = groups.len(), "a barcode names releases in several groups, so it names none");
        return None;
    }

    let taken = barcoded.into_iter().next()?;
    Some(NamedAlbum {
        group: taken.group?,
        release: Some(taken.release),
        title: taken.title,
        credit: taken.credit,
    })
}

pub(crate) fn album_held(connection: &Connection, named: &NamedAlbum) -> Result<Option<Linked>> {
    let held = connection
        .query_row(
            HELD_ALBUM,
            params![
                named.group.as_str(),
                named.release.as_ref().map(Mbid::as_str)
            ],
            |row| {
                Ok((
                    row.get::<_, i64>(0)?,
                    row.get::<_, String>(1)?,
                    row.get::<_, Option<String>>(2)?,
                    row.get::<_, i64>(3)?,
                ))
            },
        )
        .optional()
        .map_err(|source| Error::store(StoreOp::Query, source))?;
    let Some((album, title, artist, missing)) = held else {
        return Ok(None);
    };

    Ok(Some(Linked::HeldAlbum {
        album: AlbumId::new(album as u64)?,
        title,
        artist,
        missing: u32::try_from(missing).unwrap_or(u32::MAX),
    }))
}

