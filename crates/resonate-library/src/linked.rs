impl Barcode {
    pub fn new(text: &str) -> Option<Self> {
        let digits = text.trim();
        let counted = BARCODE_DIGITS_AT_LEAST..=BARCODE_DIGITS_AT_MOST;

        (counted.contains(&digits.len()) && digits.bytes().all(|byte| byte.is_ascii_digit()))
            .then(|| Self(digits.to_owned()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    pub fn names(&self, stated: &str) -> bool {
        let stated = stated.trim();
        stated.bytes().all(|byte| byte.is_ascii_digit())
            && stated.trim_start_matches(PADDING) == self.0.trim_start_matches(PADDING)
    }

    pub fn spellings(&self) -> Vec<String> {
        let significant = self.0.trim_start_matches(PADDING);
        let mut spellings = vec![self.0.clone()];
        for width in [UPC_DIGITS, EAN_DIGITS] {
            let spelt = format!("{significant:0>width$}");
            if !spellings.contains(&spelt) {
                spellings.push(spelt);
            }
        }
        spellings
    }
}

impl fmt::Display for Barcode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

fn names_a_song(address: &Address<'_>) -> bool {
    let first = address.first();
    let segments = address.segments.as_slice();

    match address.host.as_str() {
        "open.spotify.com" | "play.spotify.com" | "tidal.com" | "listen.tidal.com" => {
            address.names_an_id_after("track")
        }
        "music.apple.com" | "itunes.apple.com" => {
            asked_for(address.query, "i").is_some_and(names_an_id) || segments.contains(&"song")
        }
        "youtube.com" | "m.youtube.com" | "music.youtube.com" => {
            first == Some("watch") && asked_for(address.query, "v").is_some_and(names_an_id)
        }
        "youtu.be" => segments.len() == 1 && names_an_id(segments[0]),
        "soundcloud.com" | "m.soundcloud.com" => match segments {
            [_, track] => !SOUNDCLOUD_PAGES_NAMING_NO_SONG.contains(track),
            _ => false,
        },
        "song.link" => !segments.is_empty(),
        "play.anghami.com" => address.names_an_id_after("song"),
        "boomplay.com" => address.names_an_id_after("songs"),
        "audiomack.com" => segments.get(1) == Some(&"song"),
        host if host.starts_with("music.amazon.") => {
            first == Some("tracks") || asked_for(address.query, "trackAsin").is_some()
        }
        host if host.starts_with("music.yandex.") => address.names_an_id_after("track"),
        _ => false,
    }
}

fn names_an_album(address: &Address<'_>) -> bool {
    match address.host.as_str() {
        "open.spotify.com" | "play.spotify.com" | "tidal.com" | "listen.tidal.com" => {
            address.names_an_id_after("album")
        }
        "music.apple.com" | "itunes.apple.com" => {
            address.names_an_id_after("album") && asked_for(address.query, "i").is_none()
        }
        "music.youtube.com" => {
            address.first() == Some("playlist")
                && asked_for(address.query, "list")
                    .is_some_and(|list| list.starts_with(YOUTUBE_MUSIC_ALBUMS) && names_an_id(list))
        }
        "album.link" => !address.segments.is_empty(),
        host if host.starts_with("music.amazon.") => {
            address.names_an_id_after("albums") && asked_for(address.query, "trackAsin").is_none()
        }
        _ => false,
    }
}

fn names_a_spotify_id(id: &str) -> bool {
    id.len() == SPOTIFY_ID_LENGTH && id.bytes().all(|byte| byte.is_ascii_alphanumeric())
}

fn names_an_id(id: &str) -> bool {
    !id.is_empty()
        && id
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-' || byte == b'_')
}

fn asked_for<'a>(query: &'a str, name: &str) -> Option<&'a str> {
    query
        .split('&')
        .find_map(|pair| pair.strip_prefix(name)?.strip_prefix('='))
}

pub(crate) enum HeldBy<'a> {
    Recording(&'a Mbid),
    Isrc(&'a Isrc),
}

pub(crate) fn held_as(connection: &Connection, held_by: HeldBy<'_>) -> Result<Option<Linked>> {
    let (sql, key) = match held_by {
        HeldBy::Recording(recording) => (HELD_BY_RECORDING, recording.as_str()),
        HeldBy::Isrc(isrc) => (HELD_BY_ISRC, isrc.as_str()),
    };

    connection
        .query_row(sql, params![key], |row| {
            Ok((row.get(0)?, row.get(1)?, row.get::<_, i64>(2)?))
        })
        .optional()
        .map_err(|source| Error::store(StoreOp::Query, source))?
        .map(|(title, artist, id)| {
            Ok(Linked::Held {
                track: TrackId::new(id as u64)?,
                title,
                artist,
            })
        })
        .transpose()
}

pub(crate) fn the_take_linked(
    takes: Vec<Recording>,
    length: Option<Duration>,
) -> Option<Recording> {
    let Some(length) = length else {
        return takes.into_iter().next();
    };
    let apart = |take: &Recording| take.length.map(|held| held.abs_diff(length));

    takes
        .into_iter()
        .filter(|take| apart(take).is_none_or(|apart| apart <= LENGTHS_AGREE_WITHIN))
        .min_by_key(|take| apart(take).unwrap_or(LENGTHS_AGREE_WITHIN))
}

